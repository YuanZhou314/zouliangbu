def esc(s):
    return s.replace("'", "''")


def q(s):
    return "'" + esc(str(s)) + "'"


def num(v):
    return f"{v:.6f}"


HEADER = """-- V9：深圳市内线路内容补齐（路线 / 正文 / 交通 / 轨迹 / 标注）
--
-- 背景：V2 只有 12 条简单种子线路，且 route_detail、route_track_point、route_marker
--       三张表完全没有数据 —— App 线路详情页点进去是空的。
--       本迁移按「优先深圳市内」补齐内容：给新增线路写入完整正文、交通、
--       40~80 个轨迹点与 3~6 个标注点，并对 V2 里那条没有正文的旧深圳线做原地扩写。
--
-- 放 common/ 目录下：sqlite(dev/test) 与 mysql(prod) 两种方言都要能跑，因此
--   - 只用标准 INSERT / UPDATE / SELECT，不写任何方言专有语法；
--   - 引用未知自增 id 一律用 `FROM route WHERE name = '...'` 之类的子查询，
--     不用 MySQL 的 LAST_INSERT_ID()，也不用 SQLite 的 last_insert_rowid()；
--   - 轨迹/标注点以「派生表 + JOIN route」的写法批量插入，避开 MySQL
--     早期版本不支持子查询出现在 INSERT ... VALUES 里的限制。
--
-- 坐标：GCJ-02（火星坐标），全部落在深圳市域经纬度范围内，符合 V3 的表约定。
--
-- 生成方式：由 zouliangbu-server/scripts/gen_shenzhen_routes.py 生成，请勿手工编辑。
"""


def gen():
    lines = [HEADER]

    # ① 分组
    lines.append("\n-- ① 深圳专属分组（sort_weight 高于通用分组，排在目录最前）")
    lines.append("INSERT INTO route_section (title, subtitle, sort_weight) VALUES")
    rows = []
    for title, subtitle, weight in SECTIONS:
        rows.append(f"({q(title)}, {q(subtitle)}, {weight})")
    lines.append(",\n".join(rows) + ";")

    # ② 线路主记录
    lines.append("\n-- ② 线路主记录（顺序 field）")
    lines.append("INSERT INTO route (name, region, distance_km, ascent_meters, cover_url, tags, section_id, is_recommend, sort_weight, status) VALUES")
    rows = []
    for idx, r in enumerate(ROUTES):
        if r.get("rename_from"):
            continue
        rows.append(
            f"({q(r['name'])}, {q(r['region'])}, {r['distance']}, {r['ascent']}, NULL, {q(r['tags'])}, "
            f"(SELECT id FROM route_section WHERE title = {q(r['section'])}), "
            f"{'TRUE' if r['recommend'] else 'FALSE'}, {r['sort']}, 1)"
        )
    lines.append(",\n".join(rows) + ";")

    # ③ 旧线原地扩写
    renamed = [r for r in ROUTES if r.get("rename_from")]
    if renamed:
        lines.append("\n-- ③ V2 里那条「有列表无详情」的旧深圳线：原地扩写为完整线路（不动 V2，只做向前更新）")
        for r in renamed:
            lines.append(
                f"UPDATE route SET name = {q(r['name'])}, region = {q(r['region'])}, "
                f"distance_km = {r['distance']}, ascent_meters = {r['ascent']}, tags = {q(r['tags'])}, "
                f"section_id = (SELECT id FROM route_section WHERE title = {q(r['section'])}), "
                f"is_recommend = {'TRUE' if r['recommend'] else 'FALSE'}, sort_weight = {r['sort']}, status = 1 "
                f"WHERE name = {q(r['rename_from'])};"
            )

    # ④ 线路详情
    lines.append("\n-- ④ 线路正文（route_detail）")
    for r in ROUTES:
        intro = "".join(f"<p>{p}</p>" for p in r["intro"])
        content = "".join(
            f"<h3>{h}</h3><p>{p}</p>" for h, p in r["content"]
        )
        lines.append(
            "INSERT INTO route_detail (route_id, intro_html, content_html, traffic_html, difficulty, risk, "
            "suitable_months, road_type, view_type, duration_name, source_url, source_name, source_author, "
            "curator_name, updated_at)\n"
            f"SELECT id, {q(intro)}, {q(content)}, {q(r['traffic'])}, {q(r['difficulty'])}, {q(r['risk'])}, "
            f"{q(r['months'])}, {q(r['road'])}, {q(r['view'])}, {q(r['duration'])}, "
            f"{q('https://www.2bulu.com/mc/route/detail?id=' + r['source_id'])}, "
            f"'两步路', {q(r['source_author'])}, '走两步内容组', CURRENT_TIMESTAMP\n"
            f"FROM route WHERE name = {q(r['name'])};"
        )

    # ⑤ 轨迹点
    lines.append("\n-- ⑤ 轨迹点（route_track_point）：每条线路一条批量插入，seq 从 0 递增")
    for ri, r in enumerate(ROUTES):
        pts = build_track(r["waypoints"], r["mode"], r["npts"], 1000 + ri, r["base"])
        first = pts[0]
        rows = [
            f"SELECT {first['seq']} AS seq, {num(first['lat'])} AS lat, {num(first['lng'])} AS lng, "
            f"{first['alt']:.1f} AS alt, {first['speed']} AS spd, {first['time']} AS tm"
        ]
        for p in pts[1:]:
            rows.append(
                f"UNION ALL SELECT {p['seq']}, {num(p['lat'])}, {num(p['lng'])}, "
                f"{p['alt']:.1f}, {p['speed']}, {p['time']}"
            )
        rows.append(f"ORDER BY seq")
        lines.append(
            f"-- {r['name']}（{len(pts)} 个轨迹点）\n"
            "INSERT INTO route_track_point (route_id, seq, lat, lng, altitude, speed, track_time)\n"
            "SELECT r.id, t.seq, t.lat, t.lng, t.alt, t.spd, t.tm\n"
            "FROM route r, (\n    " + "\n    ".join(rows) + "\n) t\n"
            f"WHERE r.name = {q(r['name'])};"
        )

    # ⑥ 标注点
    lines.append("\n-- ⑥ 标注点（route_marker）：登山口 / 岔路 / 补给点 / 观景平台 / 山顶 / 下撤点")
    for r in ROUTES:
        rows = []
        for seq, (name, lat, lng, alt) in enumerate(r["markers"]):
            tm = int(datetime.strptime(r["base"], "%Y-%m-%d %H:%M").replace(tzinfo=CST).timestamp() * 1000) \
                 + seq * 1800000
            rows.append(
                f"SELECT {seq} AS seq, {q(name)} AS name, {num(lat)} AS lat, {num(lng)} AS lng, "
                f"{float(alt):.1f} AS alt, {tm} AS tm"
            )
        lines.append(
            f"-- {r['name']}（{len(rows)} 个标注点）\n"
            "INSERT INTO route_marker (route_id, seq, name, lat, lng, altitude, marker_time)\n"
            "SELECT r.id, t.seq, t.name, t.lat, t.lng, t.alt, t.tm\n"
            "FROM route r, (\n    " + "\n    UNION ALL ".join(rows) + "\n) t\n"
            f"WHERE r.name = {q(r['name'])};"
        )

    sql = "\n".join(lines) + "\n"
    os.makedirs(os.path.dirname(OUT_SQL), exist_ok=True)
    with open(OUT_SQL, "w", encoding="utf-8") as f:
        f.write(sql)
    return sql


