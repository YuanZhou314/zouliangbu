def meters_between(a, b):
    """两点间平面距离（米），近似即可。"""
    dx = (b[1] - a[1]) * 96000.0          # 深圳纬度下 1 经度约 96000 米
    dy = (b[0] - a[0]) * 111000.0
    return math.hypot(dx, dy)


def expand_waypoints(waypoints, mode):
    waypoints = list(waypoints)
    if mode == "outback":
        return waypoints + waypoints[-2::-1]          # 原路返回
    if mode == "loop":
        return waypoints + [waypoints[0]]             # 闭合环线
    return waypoints                                  # traverse 单向穿越


def build_track(waypoints, mode, npts, seed, base_dt):
    """等距重采样 + 海拔插值 + 轻微横向扰动 + 依坡度推算速度时间。"""
    pts = expand_waypoints(waypoints, mode)
    rnd = random.Random(seed)

    seg = []
    total = 0.0
    for i in range(len(pts) - 1):
        d = meters_between(pts[i], pts[i + 1])
        seg.append(d)
        total += d
    assert total > 0, "航点距离为零"

    step = total / (npts - 1)
    out = []
    acc = 0.0
    si = 0
    for i in range(npts):
        target = i * step
        while si < len(seg) - 1 and acc + seg[si] < target - 1e-9:
            acc += seg[si]
            si += 1
        f = 0.0 if seg[si] <= 0 else min(1.0, (target - acc) / seg[si])
        a, b = pts[si], pts[si + 1]
        lat = a[0] + (b[0] - a[0]) * f
        lng = a[1] + (b[1] - a[1]) * f
        alt = a[2] + (b[2] - a[2]) * f
        # 轻微横向扰动：模拟真实 GPS 轨迹的蜿蜒（幅度约 5~8 米）
        jitter = 0.000055 * math.sin(i * 0.9 + seed % 7) + 0.00002 * math.sin(i * 2.7)
        out.append({
            "seq": i,
            "lat": lat + jitter,
            "lng": lng - jitter * 0.8,
            "alt": alt + 1.6 * math.sin(i * 1.3) + 0.8 * math.sin(i * 0.37),
        })

    # 速度按坡度反推：爬坡慢、平路中、下坡略快
    base_ms = int(datetime.strptime(base_dt, "%Y-%m-%d %H:%M").replace(tzinfo=CST).timestamp() * 1000)
    t = base_ms
    for i, p in enumerate(out):
        if i == 0:
            p["speed"] = 0.9
            p["time"] = base_ms
            continue
        prev = out[i - 1]
        d = meters_between((prev["lat"], prev["lng"], 0), (p["lat"], p["lng"], 0))
        dalt = p["alt"] - prev["alt"]
        slope = dalt / d if d > 0 else 0.0
        speed = 1.15 - 2.6 * max(slope, 0.0) - 0.35 * max(-slope, 0.0)
        speed = max(0.45, min(1.65, speed))
        t += int(d / speed * 1000)
        p["speed"] = round(speed, 2)
        p["time"] = t
    return out


