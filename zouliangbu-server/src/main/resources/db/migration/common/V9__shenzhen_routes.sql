-- ⑥ 下线「空壳线路」：V2 的旧种子只有主记录、没有正文/轨迹/标注，
--    App 点进去是空详情页（用户反馈"线路详情什么都没有"）。
--    先置 status=0 下线，保证线路页里每一条点开都有完整内容；
--    后续补齐内容后把 status 改回 1 即可重新上线。
-- 用 NOT IN（子查询只查 route_detail）而不是 NOT EXISTS 关联 route.id：
-- MySQL 对「UPDATE 目标表同时出现在子查询里」有 1093 限制，这种写法两种方言都安全。
UPDATE route
SET status = 0
WHERE status = 1
  AND id NOT IN (SELECT route_id FROM route_detail WHERE route_id IS NOT NULL);
